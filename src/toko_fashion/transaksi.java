    private void loadData() {
        try {
            String query = "SELECT * FROM riwayat_transaksi";
            statement = (PreparedStatement) conn.prepareStatement(query);
            ResultSet rs = statement.executeQuery();
            DefaultTableModel model = (DefaultTableModel) tabelTransaksi.getModel();
            model.setRowCount(0);

            while (rs.next()) {
                int idTransaksi = rs.getInt("id_transaksi");
                String namaBarang = rs.getString("nama_barang");
                double hargaBarang = rs.getDouble("harga_barang");
                int jumlahBarang = rs.getInt("jumlah");
                String ukuran = rs.getString("ukuran");
                double totalHarga = rs.getDouble("total_harga");
                String jenisPembayaran = rs.getString("jenis_pembayaran");
                double kembalian = rs.getDouble("kembalian");
                String tanggal = rs.getString("tanggal");

                model.addRow(new Object[]{idTransaksi, namaBarang, hargaBarang, jumlahBarang, ukuran, totalHarga, jenisPembayaran, kembalian, tanggal});
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    private void cariTransaksi() {
        String keyword = txtCari.getText().trim();
        String filter = this.filter.getSelectedItem().toString();

        String query = "SELECT * FROM riwayat_transaksi WHERE ";

        switch (filter) {
            case "ID Transaksi":
                query += "id_transaksi LIKE ?";
                break;
            case "Nama Barang":
                query += "nama_barang LIKE ?";
                break;
            case "Jenis Pembayaran":
                query += "jenis_pembayaran LIKE ?";
                break;
            case "Tanggal Transaksi":
                query += "tanggal LIKE ?";
                break;
        }

        try {
            statement = (PreparedStatement) conn.prepareStatement(query);
            statement.setString(1, "%" + keyword + "%");
            ResultSet rs = statement.executeQuery();
            DefaultTableModel model = (DefaultTableModel) tabelTransaksi.getModel();
            model.setRowCount(0);

            while (rs.next()) {
                int idTransaksi = rs.getInt("id_transaksi");
                String namaBarang = rs.getString("nama_barang");
                double hargaBarang = rs.getDouble("harga_barang");
                int jumlahBarang = rs.getInt("jumlah");
                String ukuran = rs.getString("ukuran");
                double totalHarga = rs.getDouble("total_harga");
                String jenisPembayaran = rs.getString("jenis_pembayaran");
                double kembalian = rs.getDouble("kembalian");
                String tanggal = rs.getString("tanggal");

                model.addRow(new Object[]{idTransaksi, namaBarang, hargaBarang, jumlahBarang, ukuran, totalHarga, jenisPembayaran, kembalian, tanggal});
            }
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Gagal mencari data: " + e.getMessage());
        }
    }
    
